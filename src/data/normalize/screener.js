function finite(value) { return typeof value === 'number' && Number.isFinite(value) ? value : null; }

export function normalizeScreener(raw = {}) {
  const rows = Array.isArray(raw.rows) ? raw.rows.map((row) => ({
    symbol: String(row?.symbol || row?.sym || '').toUpperCase(),
    sym: String(row?.symbol || row?.sym || '').toUpperCase(),
    name: row?.name || row?.company || '',
    index: row?.index || null,
    signal: row?.signal || null,
    memo: row?.memo || null,
    score: finite(row?.score),
    rank: finite(row?.rank),
    sector: row?.sector || null,
    source: row?.source || 'screener-artifact',
    sourceKind: row?.sourceKind || null,
    allowedUse: row?.allowedUse || null,
    price: finite(row?.price),
    pctFrom52wLow: finite(row?.pctFrom52wLow),
    pctFrom52wHigh: finite(row?.pctFrom52wHigh),
    adrPct: finite(row?.adrPct),
    avgVolume30d: finite(row?.avgVolume30d),
    dollarVolume30d: finite(row?.dollarVolume30d),
    lastVolume: finite(row?.lastVolume),
    dollarVolume: finite(row?.dollarVolume),
    ema8: finite(row?.ema8),
    ema21: finite(row?.ema21),
    ema60: finite(row?.ema60),
    mcap: finite(row?.mcap),
    _mcapObservedAt: row?._mcapObservedAt || null,
    rsi: finite(row?.rsi),
    ret1m: finite(row?.ret1m),
    ret3m: finite(row?.ret3m),
    ret6m: finite(row?.ret6m),
    vol: finite(row?.vol),
    rvol20: finite(row?.rvol20 ?? row?.rvol),
    benchmarkRet: finite(row?.benchmarkRet),
    benchmarkRelativeStrength: finite(row?.benchmarkRelativeStrength),
    pctSma50: finite(row?.pctSma50),
    pctSma200: finite(row?.pctSma200),
    kalmanVel: finite(row?.kalmanVel),
    kalmanPt: finite(row?.kalmanPt),
    kalmanInnovZ: finite(row?.kalmanInnovZ),
    kalmanVelConf: finite(row?.kalmanVelConf),
    kalmanScale: row?.kalmanScale || null,
    vcpScore: finite(row?.vcpScore),
    vcpStage: row?.vcpStage || null,
    vcpPivot: finite(row?.vcpPivot),
    pe: finite(row?.pe),
    pb: finite(row?.pb),
    evEbitda: finite(row?.evEbitda),
    roe: finite(row?.roe),
    margin: finite(row?.margin),
    revGrowth: finite(row?.revGrowth),
    newsMemo: row?.newsMemo || null,
    newsTs: row?.newsTs || null,
    _fundamentalSource: row?._fundamentalSource || null,
    _fundamentalModel: row?._fundamentalModel || null,
    _fundamentalPeriod: row?._fundamentalPeriod || null,
    _fundamentalObservedAt: row?._fundamentalObservedAt || null,
    _fundamentalFiledAt: row?._fundamentalFiledAt || null,
    _fundamentalFetchedAt: row?._fundamentalFetchedAt || null,
    _fundamentalAccession: row?._fundamentalAccession || null,
    observedAt: row?.observedAt || null,
    fetchedAt: row?.fetchedAt || null,
    instrumentRef: row?.instrumentRef && typeof row.instrumentRef === 'object' ? { ...row.instrumentRef } : null,
    fieldReadiness: row?.fieldReadiness && typeof row.fieldReadiness === 'object' ? {
      instrumentRef: row.fieldReadiness.instrumentRef ? { ...row.fieldReadiness.instrumentRef } : null,
      fields: row.fieldReadiness.fields && typeof row.fieldReadiness.fields === 'object' ? Object.fromEntries(Object.entries(row.fieldReadiness.fields).map(([key, value]) => [key, { ...value }])) : {},
      coverage: row.fieldReadiness.coverage && typeof row.fieldReadiness.coverage === 'object' ? { ...row.fieldReadiness.coverage, counts: { ...(row.fieldReadiness.coverage.counts || {}) } } : null
    } : null,
    fieldObservations: Array.isArray(row?.fieldObservations) ? row.fieldObservations.map((observation) => ({ ...observation })) : [],
    setupProfile: row?.setupProfile && typeof row.setupProfile === 'object' ? { ...row.setupProfile } : null,
    factorScores: row?.factorScores && typeof row.factorScores === 'object' ? { ...row.factorScores } : {},
    quantSignal: row?.quantSignal || null,
    _compositeZ: finite(row?._compositeZ)
  })).filter((row) => row.symbol) : [];
  return Object.freeze({
    rows,
    filters: raw.filters && typeof raw.filters === 'object' ? { ...raw.filters } : {},
    metadata: raw.metadata && typeof raw.metadata === 'object' ? { ...raw.metadata } : {},
    revision: raw.revision || null,
    snapshotId: raw.snapshotId || raw.metadata?.snapshotId || null,
    status: raw.status || (rows.length ? 'current' : 'unavailable'),
    updatedAt: raw.updatedAt || new Date().toISOString()
  });
}
