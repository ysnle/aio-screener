import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { selectSecFundamentalsAsOf } from '../../src/domain/fundamental/sec-report.js';
import { secFundamentalRowFields } from '../../src/domain/fundamental/sec-row-fields.js';
import { buildFiscalRead } from '../../src/domain/fundamental/fiscal-read.js';
import { buildLensRead, buildPeerStrengths } from '../../src/domain/fundamental/stock-lens.js';
import { reverseDcfInputs, buildMarginCashRead } from '../../src/domain/fundamental/analysis-read.js';
import { buildConsensusPoint } from '../../src/domain/fundamental/consensus-read.js';
const now = Date.parse('2026-10-29T00:00:00Z');
const obs = value => ({value, periodStart:'2025-01-01', periodEnd:'2025-12-31', filedAt:'2026-02-01', form:'20-F'});
const foreignPit = selectSecFundamentalsAsOf({symbol:'TEST', reportingCurrency:'EUR', form:'20-F', pit:{currency:'EUR', observations:{revenue:[obs(1000)], netIncome:[obs(100)], equity:[obs(500)], sharesOutstanding:[obs(100)]}}}, '2026-10-28', {priceAsOf:100});
assert.equal(foreignPit.pe,100);
assert.equal(foreignPit.reportingCurrency,undefined);
const oldClose = reverseDcfInputs({history:[{periodEnd:'2025-12-31',operatingCashFlow:100,capex:10}], fundamentals:{sharesOutstanding:10,sharesObservedAt:'2026-02-01',sharesCheck:'scale-mismatch'},close:{value:100,date:'1990-01-01'},nowMs:now});
assert.equal(oldClose.state,'ready');
const history = [{periodEnd:'2022-12-31', revenue:100,netIncome:10,equity:100},{periodEnd:'2025-12-31',revenue:200,netIncome:20,equity:100}];
const gapLens = buildLensRead({history,lens:{id:'general'}});
const guardedFiscal = buildFiscalRead({symbol:'TEST',fundamentals:{symbol:'TEST',fiscalHistory:history},now});
assert.equal(guardedFiscal.lastGrowth,null);
assert.match(gapLens.rows.find(x=>x.id==='revenueGrowth').value,/100.0%/);
const ties = buildPeerStrengths([{self:true,growth:10},{growth:10},{growth:10},{growth:10}]);
assert.equal(ties.strengths.length,1);
assert.equal(ties.strengths[0].rank,1);
const flat = buildFiscalRead({symbol:'TEST',fundamentals:{symbol:'TEST',fiscalHistory:[{periodEnd:'2024-12-31',revenue:100,netIncome:0,equity:100,operatingCashFlow:0},{periodEnd:'2025-12-31',revenue:100,netIncome:0,equity:100,operatingCashFlow:0}]},now});
assert.match(flat.points.find(x=>x.id==='growth').text,/줄었습니다/);
assert.match(flat.points.find(x=>x.id==='cash').text,/순손실과 영업현금 유출/);
const cash = buildMarginCashRead([{periodEnd:'2025-12-31',capitalChain:true,revenue:100,cash:50,longTermDebt:10,shortTermInvestments:null,buybacks:20,dividends:null,operatingCashFlow:100,capex:10}]);
assert.equal(cash.capital.returned,20);
const consensus = buildConsensusPoint({valuationPrice:100,factorSessionDate:'2026-10-28',pctFrom52wHigh:-20,ret1m:20},{asOf:'2026-10-28',fwd:{eps:10,from:'2026-12',to:'2027-09',up4w:3,down4w:0},trailing:{eps:10}},{now});
assert.match(consensus.text,/가격과 이익 전망이 반대/);
const future = secFundamentalRowFields({observedAt:'2099-12-31',filedAt:'2100-02-01',roe:20},{factorSessionDate:'2026-10-28',nowMs:now});
assert.equal(future.fundamentalQuality.status,'CURRENT');
const report={scope:'Pure local fixtures; no external requests or product writes',foreignPit,oldClose,gapLens,guardedGrowth:guardedFiscal.lastGrowth,ties,flat:flat.points,cash,consensus,future};
writeFileSync(new URL('./pass19-reproductions.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log('PASS19: 8 counterexample groups reproduced; see pass19-reproductions.json');
