// Audit-only counterexamples; no producer, network, or product writes.
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { readScreenerBreadth } from '../../src/domain/market/screener-breadth.js';
import { buildSectorMap } from '../../src/domain/market/sector-map.js';
import { diagnoseBreadthConsensus } from '../../src/domain/market/breadth-consensus.js';
import { buildIndexEarnings } from '../../src/domain/market/index-earnings.js';
import { formatSlotMove } from '../../src/domain/market/market-timeline.js';
import { scoreRelease } from '../../src/domain/market/macro-crossroads.js';
import { buildScenarioOutlook } from '../../src/domain/market/scenario-outlook.js';
import { rrgSettledQuadrant } from '../../src/domain/themes/recent-check.js';
const now = Date.parse('2026-10-29T00:00:00Z');
const segment = { above5: 50, above20: 50, above50: 50, above200: 50, advanceRatio: .5, coveragePct: 95, eligible: 500, observedAt: '2026-10-28T20:00:00Z' };
const root = { schemaVersion: '1.0', segments: { us: segment, kr: { ...segment, observedAt: undefined } } };
const missingKrDate = readScreenerBreadth(root, now);
assert.ok(missingKrDate.kr);
assert.equal(missingKrDate.kr.ts, 0);
const staleSp = readScreenerBreadth({ ...root, segments: { ...root.segments, sp500: { ...segment, observedAt: '2026-10-01T20:00:00Z' } } }, now);
assert.equal(staleSp.state.status, 'blocked');
assert.equal(readScreenerBreadth(root, now).state.status, 'verified_current');
const rows = Array.from({ length: 20 }, (_, i) => ({ sym: `TEST${i}`, sector: 'Technology', index: 'SP500', referenceMarketCap: { billions: 1 }, ret1d: 1, factorSessionDate: '2026-10-28' }));
const missingTurnover = buildSectorMap({ rows });
const turnoverControl = buildSectorMap({ rows: rows.map(row => ({ ...row, dollarVolume30d: 1e7 })) });
assert.equal(missingTurnover.available, false);
assert.equal(turnoverControl.available, true);
const registry = { BREADTH: { getLabel: v => ({ signal: v === 0 ? 'capitulation' : 'mixed', label: 'fixture' }) } };
const nullConsensus = diagnoseBreadthConsensus({ sma5: null, sma20: null, sma50: null }, registry);
assert.equal(nullConsensus.verdict, '강세 합의');
assert.equal(diagnoseBreadthConsensus({}, registry).verdict, '—');
const futureClose = buildIndexEarnings({ now, rows: [{ sym: 'TEST', valuationPrice: 100, factorSessionDate: '2099-01-01' }], weights: { rows: [{ sym: 'TEST', weight: 100 }] }, consensus: { rows: { TEST: { asOf: '2026-10-28', fwd: { eps: 5, up4w: 1, down4w: 0 } } } } });
assert.equal(futureClose.forwardPe, 20);
const nullMove = formatSlotMove({ label: 'TEST', change: null });
assert.equal(nullMove.text, '0.00%');
const missingUnemployment = scoreRelease('us-nfp', { payroll: 100, unempDelta: null });
const belowUnemploymentBand = scoreRelease('us-nfp', { payroll: 100, unempDelta: -.5 });
assert.ok(missingUnemployment.some(x => x.branchId === 'softland'));
assert.ok(belowUnemploymentBand.some(x => x.branchId === 'softland'));
const border = { symbol: 'XLK', label: '기술', rsRatio: 100.2, rsMomentum: 100.2, quadrant: 'Leading' };
assert.equal(rrgSettledQuadrant(border), 'Border');
const borderOutlook = buildScenarioOutlook({ scenarios: { available: true, asOf: '2026-10-28', scenarios: [{ id: 'expansion' }] }, regime: { available: true, axes: [] }, sectors: [border] });
assert.equal(borderOutlook.items[0].opportunityLinks.length, 0);
const report = { scope: 'Local pure-function counterexamples, not proof of production occurrence', missingKrDate, staleSp, missingTurnover, turnoverControl: { available: turnoverControl.available }, nullConsensus, futureClose, nullMove, missingUnemployment, belowUnemploymentBand, borderLinks: borderOutlook.items[0].opportunityLinks };
writeFileSync(new URL('./pass17-reproductions.json', import.meta.url), JSON.stringify(report, null, 2) + '\n');
