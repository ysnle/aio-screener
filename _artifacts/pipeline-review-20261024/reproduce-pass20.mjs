import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { normalizeNewsItem, NEWS_SURFACE_CONTRACTS, buildNewsSurfaceModel, scoreItem, newsSourceTier } from '../../src/domain/news/selection.js';
import { reportVerification } from '../../src/domain/news/report-verification.js';
import { selectIntradayNews } from '../../src/domain/news/stories.js';
import { computeNewsSentimentScore, computeNewsRiskSignals } from '../../src/domain/news/scoring.js';
import { companyMatcher } from '../../src/domain/briefing/news-picks.js';
const now=Date.parse('2026-10-30T00:00:00Z');
const base={title:'Market chatter: chip acquisition rumor',summary:'A speculative acquisition report with no official confirmation or named source for the proposed transaction.',source:'Reuters',tier:1,score:99,topic:'equity',pubDate:'2026-10-29T23:30:00Z'};
const rumor=normalizeNewsItem('briefing',base,NEWS_SURFACE_CONTRACTS.briefing,now,null);
assert.equal(reportVerification(base.title),'rumor');
assert.equal(rumor.eligibleForAi,true);
const future={...base,title:'Federal Reserve policy announcement',pubDate:'2026-10-31T01:00:00Z',_serverBackstop:true,newsCyclePolicy:'kst-0800-completed-24h',newsCycleStart:'2026-10-31T00:00:00Z',newsCycleEnd:'2026-11-01T00:00:00Z'};
const futureModel=buildNewsSurfaceModel('briefing',[future],{nowMs:now,windowStart:now-86400000,windowEnd:now});
assert.equal(futureModel.aiItems.length,1);
assert.equal(futureModel.aiItems[0].currentEvidence.current,false);
const cache=new Map();
const news={title:'Federal Reserve inflation outlook',source:'Reuters',tier:1,pubDate:'2026-10-29T23:30:00Z',desc:'Federal Reserve rate policy and inflation'};
const initial=scoreItem({...news},{cache,now:()=>now});
const agedCached=scoreItem({...news},{cache,now:()=>now+5*86400000});
const agedFresh=scoreItem({...news},{now:()=>now+5*86400000});
assert.equal(initial,agedCached);
assert.notEqual(agedCached,agedFresh);
const canonical=[{title:'Chip company revenue jumps',link:'https://example.test/article',pubDate:'2026-10-29T20:00:00Z'}];
const revision={title:'Correction: chip company revenue fell',link:'https://example.test/article',pubDate:'2026-10-29T23:30:00Z',correctionOf:'original'};
const intraday=selectIntradayNews([revision],{canonical,cycleEndMs:now-3600000,nowMs:now});
assert.equal(intraday.length,0);
const bodyRows=Array.from({length:5},(_,i)=>({title:`Company update ${i}`,summary:'Earnings surge and rally as shares soar to record high on strong recovery.',pubDate:'2026-10-29T23:30:00Z'}));
const bodySentiment=computeNewsSentimentScore({items:bodyRows,now});
assert.equal(bodySentiment.sampleSufficient,true);
assert.equal(bodySentiment.score,50);
const negationRows=Array.from({length:5},(_,i)=>({title:`Bank reports no credit stress or default risk ${i}`,summary:'The bank reports stable credit conditions with no evidence of a deterioration in its portfolio.',pubDate:'2026-10-29T23:30:00Z'}));
const negationRisk=computeNewsRiskSignals({items:negationRows,now,windowStart:'2026-10-29T00:00:00Z',windowEnd:'2026-10-30T00:00:00Z'});
assert(negationRisk.some(x=>x.type==='credit'));
const tier=newsSourceTier({source:'Software News'});
assert.equal(tier,1);
const classMismatch=companyMatcher('BRK','').test('$BRK.B earnings');
assert.equal(classMismatch,true);
const report={scope:'Pure local contract counterexamples; live producer occurrence unverified',rumor:{reported:reportVerification(base.title),status:rumor.verificationStatus,ai:rumor.eligibleForAi},future:futureModel.aiItems[0],cache:{initial,agedCached,agedFresh},intraday,bodySentiment,negationRisk,tier,classMismatch};
writeFileSync(new URL('./pass20-reproductions.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log('PASS20: 8 local counterexample groups reproduced');
