import fs from 'node:fs';
import assert from 'node:assert/strict';
import { resolveMarketCalendarSession } from '../../src/domain/market/market-calendar.js';
import { marketClock, buildSessionBridge, koreaLinks } from '../../src/domain/market/session-bridge.js';
const special = resolveMarketCalendarSession({market:'KR',date:'2026-11-19'});
const clock = marketClock(Date.parse('2026-11-19T09:30:00+09:00'));
assert.equal(special.open,'10:00');
assert.equal(clock.kr.phase,'regular');
const common = {kospi:{change:1,observedAt:'2026-10-28T06:30:00Z'},nasdaq:{change:1,observedAt:'2026-10-27T20:00:00Z'}};
const aligned = koreaLinks({...common,kosdaq:{change:1,observedAt:'2026-10-28T06:30:00Z'}});
const mismatched = koreaLinks({...common,kosdaq:{change:-8,observedAt:'2026-10-26T06:30:00Z'},semis:{change:20,observedAt:'2026-10-29T20:00:00Z'}});
assert.equal(aligned.find(row=>row.id==='local').verdict,'against');
assert.equal(mismatched.find(row=>row.id==='local').verdict,'supports');
assert(mismatched.find(row=>row.id==='us').evidence.includes('+20.0%'));
const future = buildSessionBridge({nowMs:Date.parse('2026-10-28T08:00:00Z'),snapshot:{quotes:[{instrumentId:'NQ=F',value:22000,changePct:2,observedAt:'2026-10-29T08:00:00Z'}]}});
assert.equal(future.readings.nq.ageMin,0);
assert.equal(future.futuresStale,false);
assert(future.futuresLine.includes('0분 전'));
fs.writeFileSync(new URL('./pass16-reproductions.json',import.meta.url),JSON.stringify({at:new Date().toISOString(),network:false,special,clock,aligned,mismatched,future},null,2)+'\n');
console.log('PASS: declared special opening ignored; cross-session KOSDAQ/SMH admitted; future futures observation shown 0 minutes old');
