import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {buildMyNames} from '../../src/domain/briefing/daily-diff.js';
import {earningsReactionCases,buildEarningsWeek,eventPreviews} from '../../src/domain/briefing/event-guide.js';
import {buildBriefingSchedule} from '../../src/domain/briefing/schedule.js';
const names=buildMyNames({symbols:['A','B'],rows:[{sym:'A',rsi:80},{sym:'B',rsi:80}],breadthState:'burden'});
assert.match(names.summary,/대부분은 아직 50일선 위/);
const sort=buildMyNames({symbols:['A','B'],live:{A:{pct:100},B:{pct:2}}});
assert.equal(sort.names[0].symbol,'A'); assert.equal(sort.names[0].daySignalled,false);
const signals=[{kind:'earnings',ticker:'TEST',post:'1',revenue:'beat',eps:'beat'}];
const nullReturn=earningsReactionCases({signals,posts:[{id:'1',datetime:'2026-10-29T12:00:00Z'}],rows:[{sym:'TEST',factorSessionDate:'2026-10-29',ret1d:null}],session:'2026-10-29'});
assert.equal(nullReturn[0].move,0);
const winter=earningsReactionCases({signals,posts:[{id:'1',datetime:'2026-12-01T14:00:00Z'}],rows:[{sym:'TEST',factorSessionDate:'2026-12-01',ret1d:-3}],session:'2026-12-01'});
assert.equal(winter.length,0);
const week=buildEarningsWeek({earnings:[{symbol:'TEST',date:'2026-10-30',hour:'bmo'},{symbol:'TEST',date:'2026-10-30',hour:'bmo'}]});
assert.equal(week.total,2);
const emptyActual=buildBriefingSchedule({earnings:[{symbol:'TEST',date:'2026-10-30',hour:'bmo',epsActual:''}],names:{TEST:'Test'},nowMs:Date.parse('2026-10-30T10:00:00Z')});
assert.equal(emptyActual[0].status,'received'); assert.match(emptyActual[0].last,/EPS 0.00/);
const preview=eventPreviews({earnings:[{symbol:'TEST',date:'2026-12-01',hour:'bmo',indexWeight:1,epsEstimate:1}],names:{TEST:'Test'},nowMs:Date.parse('2026-12-01T18:30:00Z')});
const winterSchedule=buildBriefingSchedule({earnings:[{symbol:'TEST',date:'2026-12-01',hour:'bmo',indexWeight:1,epsEstimate:1}],names:{TEST:'Test'},nowMs:Date.parse('2026-12-01T18:30:00Z')});
assert.equal(preview.length,0); assert.equal(winterSchedule.length,1);
writeFileSync(new URL('./pass26-reproductions.json',import.meta.url),JSON.stringify({names,sort,nullReturn,winter,week,emptyActual,preview,winterSchedule},null,2)+'\n');
