import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {createLearningState} from '../../src/domain/knowledge/learning-state.js';
import {createEvidenceRegistry,createClaimRegistry} from '../../src/domain/knowledge/evidence.js';
import {normalizeKnowledgeEdge,inspectKnowledgeGraph} from '../../src/domain/knowledge/graph.js';
import {isOverdue} from '../../src/domain/knowledge/knowledge-cadence.js';
import {typedRelations} from '../../src/domain/knowledge/atlas-relations.js';
const data=new Map(); const storage={getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v)};
const a=createLearningState({storage}),b=createLearningState({storage});
a.setNote('a','first'); b.setNote('b','second');
const reloaded=createLearningState({storage}).snapshot(); assert.equal(reloaded.notes.a,undefined);
const evidence=createEvidenceRegistry([{id:'s',url:'https://example.com',verification:'verified',reviewedAt:'2020-01-01',allowedUse:'ANY'}],[{id:'s',url:'https://example.com',verification:'revoked',reviewedAt:'2026-10-30',allowedUse:'NONE'}]);
assert.equal(evidence.resolve('s').verification,'verified'); assert.equal(evidence.conflicts.length,0);
const claims=createClaimRegistry([{id:'c',sourceIds:[]}],evidence);assert.equal(claims.unresolved.length,0);
const edge=normalizeKnowledgeEdge({from:'a',to:'b',relation:'참고'},{reviewedAt:'2026-10-30'});
assert(edge.inferredFields.length>0);
const inspected=inspectKnowledgeGraph({nodeIds:['a','b'],edges:[edge]});assert.equal(inspected.inferredEdges.length,0);
const second=normalizeKnowledgeEdge({...edge,type:'CAUSES',id:undefined});
assert.equal(second.id,edge.id);
const duplicateIds=inspectKnowledgeGraph({nodeIds:['a','b'],edges:[edge,second]});assert.equal(duplicateIds.duplicateEdges.length,0);
const future=isOverdue('observation','2099-01-01',Date.parse('2026-10-30'));assert.equal(future,false);
const relations=typedRelations({nodes:[{nodeId:'a'},{nodeId:'b'}],relationshipModel:{crossDomainEdges:[{id:'unknown',from:'a',to:'b',type:'EXPOSES_TO',conditions:['only in X'],sourceIds:['s']}]}});
assert.equal(relations.get('a')[0].type,'substitute');assert.equal(relations.get('a')[0].conditions,undefined);
writeFileSync(new URL('./pass29-reproductions.json',import.meta.url),JSON.stringify({reloaded,evidence:evidence.sources,claims:claims.claims,edge,inspected,duplicateIds,future,relations:[...relations]},null,2)+'\n');
