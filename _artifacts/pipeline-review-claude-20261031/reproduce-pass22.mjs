import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { createCompositionSnapshot, deriveRiskEstimate, assessAccountPerformance } from '../../src/domain/portfolio/risk.js';
import { convertCashBalances } from '../../src/domain/portfolio/cash.js';
import { resolveFxRate } from '../../src/domain/portfolio/fx.js';
import { _calcDailyReturns, _btVarOrderAudit, _pearsonCorr } from '../../src/domain/portfolio/return-stats.js';
import { lookThrough } from '../../src/domain/portfolio/look-through.js';
const snapshot=createCompositionSnapshot({members:[{ticker:'X',qty:1,price:100}],cash:{amount:0,currency:'USD'},baseCurrency:'USD'});
const invalid=deriveRiskEstimate({snapshot,exposureHistoryMode:'current_composition_retrospective',returnsMap:{X:[NaN,.1]}});
assert.equal(invalid.status,'ready'); assert(Number.isNaN(invalid.publishedReturns[0]));
const coverage=Object.fromEntries(['trades','deposits-withdrawals','dividends-splits','fees-taxes','fx','valuation-cuts'].map(k=>[k,true]));
const account=assessAccountPerformance({ledger:{coverage,currency:'USD',dayCount:'actual-365',flowTiming:'end-of-period',valuations:[{date:'2025-01-01',amount:100},{date:'2026-01-01',amount:200}],transactions:[{date:'2025-06-01',kind:'deposit',amount:'bad'}]}});
assert.equal(account.status,'ready'); assert.equal(account.twr,1); assert.equal(account.twrExact,true);
const cash=convertCashBalances({balances:[{currency:'USD',amount:100},{currency:'KRW',amount:'bad'}],target:'USD'});
assert.equal(cash.ok,true); assert.equal(cash.total,100);
const legs=[{from:'USD',to:'KRW',rate:1200,observedAt:'2020-01-01',source:'old'},{from:'KRW',to:'USD',rate:1/1400,observedAt:'2026-10-29',source:'new'}];
const fx=resolveFxRate(legs,{from:'USD',to:'KRW',asOfMs:Date.parse('2026-10-30')});
assert.equal(fx.reason,'rate-stale');
const order=_btVarOrderAudit([.1,.2],'unspecified',[null,null]); assert.equal(order.state,'verified');
const infReturns=_calcDailyReturns([100,Infinity,110]); assert(!infReturns.every(Number.isFinite));
assert.equal(_pearsonCorr([1,1,1],[1,2,3]),0);
const sp500={rows:[{sym:'NVDA',weight:100,sector:'Technology'}],asOf:'2026-10-29'};
const holdings=[{symbol:'NVDA',value:100,sector:null},{symbol:'SPY',value:100}];
const orderA=lookThrough({rows:holdings,sp500});
const orderB=lookThrough({rows:holdings.slice().reverse(),sp500});
assert.notEqual(orderA.exposures[0].sector,orderB.exposures[0].sector);
writeFileSync(new URL('./pass22-reproductions.json',import.meta.url),JSON.stringify({scope:'Pure boundary counterexamples, consumer reach not certified',invalid,account,cash,fx,order,infReturns,undefinedCorrelation:0,sectorByOrder:[orderA.sectors,orderB.sectors]},(_k,v)=>typeof v==='number'&&!Number.isFinite(v)?String(v):v,2)+'\n');
console.log('PASS22: 8 contract counterexample groups reproduced');
