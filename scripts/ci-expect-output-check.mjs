#!/usr/bin/env node
// scripts/ci-expect-output-check.mjs — v59.42
//
// Expect tests: each `scripts/fixtures/expect/<suite>.cases.mjs` runs pure domain functions on fixed inputs and the
// full printed result is kept next to it in `<suite>.expect.md`. A change to what users read (labels, readings,
// withheld text) then shows up as a reviewable diff of that file instead of a regex that checks one fragment.
// The pattern follows the React compiler fixtures (input + `.expect.md` output, regenerated, diff reviewed) and
// expect tests as described by Ron Minsky (2026-10): print the behaviour, capture it, review the change.
//
// Usage:
//   node scripts/ci-expect-output-check.mjs            # verify every suite
//   node scripts/ci-expect-output-check.mjs --update   # rewrite the .expect.md files, then review `git diff`

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'scripts/fixtures/expect');
const update = process.argv.includes('--update');
const errors = [];
const check = (label, condition, detail = '') => { if (!condition) errors.push(label + (detail ? `: ${detail}` : '')); };
const load = (rel) => import(pathToFileURL(join(root, rel)));
const fence = (lang, body) => ['```' + lang, body, '```'].join('\n');

function render(suite, cases) {
  const lines = [`# ${suite.name} — expect output`, '', `Source: \`${suite.source}\`. Generated by \`node scripts/ci-expect-output-check.mjs --update\`; do not edit by hand.`];
  for (const item of cases) {
    const output = typeof item.output === 'string' ? item.output : JSON.stringify(item.output, null, 2);
    lines.push('', `## ${item.name}`, '', '### Input', '', fence('json', JSON.stringify(item.input ?? null, null, 2)), '', '### Output', '', fence('text', output));
  }
  return lines.join('\n') + '\n';
}

function firstDifference(expected, actual) {
  const a = expected.split('\n');
  const b = actual.split('\n');
  const at = a.findIndex((line, index) => line !== b[index]);
  const index = at === -1 ? Math.min(a.length, b.length) : at;
  const show = (list) => list.slice(Math.max(0, index - 2), index + 4).map((line, offset) => `    ${Math.max(0, index - 2) + offset + 1}| ${line}`).join('\n');
  return `first difference at line ${index + 1}\n  expected:\n${show(a)}\n  actual:\n${show(b)}`;
}

const suites = existsSync(dir) ? readdirSync(dir).filter((name) => name.endsWith('.cases.mjs')).sort() : [];
check('v59.42 expect suites exist', suites.length > 0, 'scripts/fixtures/expect/*.cases.mjs');
let changed = 0;
for (const file of suites) {
  const module = await load(`scripts/fixtures/expect/${file}`);
  const suite = module.suite || {};
  check(`v59.42 ${file} names its suite and source module`, suite.name && suite.source && existsSync(join(root, suite.source)), JSON.stringify(suite));
  const cases = await module.default({ load });
  const names = cases.map((item) => item.name);
  check(`v59.42 ${file} has unique case names`, new Set(names).size === names.length, names.join(', '));
  const text = render(suite, cases);
  const expectPath = join(dir, file.replace(/\.cases\.mjs$/, '.expect.md'));
  const current = existsSync(expectPath) ? readFileSync(expectPath, 'utf8').replace(/\r\n/g, '\n') : null;
  if (update) {
    if (current !== text) { writeFileSync(expectPath, text); changed += 1; console.log(`updated ${file.replace(/\.cases\.mjs$/, '.expect.md')}`); }
    continue;
  }
  check(`v59.42 ${file} has a recorded .expect.md`, current !== null, 'run with --update and review the new file');
  if (current !== null) check(`v59.42 ${file} output matches its .expect.md`, current === text, `${firstDifference(current, text)}\n  If the new output is intended, run --update and review the diff.`);
}
for (const name of existsSync(dir) ? readdirSync(dir).filter((entry) => entry.endsWith('.expect.md')) : []) {
  check(`v59.42 ${name} has a cases file`, suites.includes(name.replace(/\.expect\.md$/, '.cases.mjs')), 'delete the orphan or restore its cases');
}

if (errors.length) {
  console.error('Expect output check failed:');
  errors.forEach((error) => console.error(` - ${error}`));
  process.exit(1);
}
console.log(update ? `Expect output updated: ${changed} of ${suites.length} suite(s) changed.` : `Expect output OK: ${suites.length} suite(s) match their .expect.md.`);
