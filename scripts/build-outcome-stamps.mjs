#!/usr/bin/env node
// Generates src/domain/scenarios/outcome-stamps.js: the definition stamps of the weekly long-history artifacts, hashed
// (src/domain/shared/definition-fingerprint.js) over the parameters and the source of the functions that compute them —
// theme stage outcomes and branch analogs (analogs.js), Nasdaq corrections and the VIX band table. A definition change
// (a parameter, or a line of a function listed here) changes its stamp; a new scoring helper belongs in its `code` list.
// Hashing runs here in Node on the source as written; the browser bundle is minified, so readers compare the generated
// constant. ci-scenario-guidance-fixture fails when the constant is behind the code.
//
//   node scripts/build-outcome-stamps.mjs [--write]     (prints the stamps; --write updates the module)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { definitionFingerprint } from '../src/domain/shared/definition-fingerprint.js';
import { ANALOG_METHOD, BRANCH_ANALOGS, OUTCOME_BANDS, THEME_OUTCOME_HORIZON, THEME_STAGE_RULE, THEME_STATES, analogScan, baseRate, quantile, summarise, themeStateOf } from '../src/domain/scenarios/analogs.js';
import { DRAWDOWN_PCT, alignCloses, analogOutcomeHistory, attachMonthlyRate, summariseOutcomes, themeStateOutcomes, windowDrawdown } from '../src/domain/scenarios/outcome-history.js';
import { CORRECTION_RULE, correctionBaseRates, correctionEpisodes } from '../src/domain/scenarios/correction-base-rates.js';
import { STRESS_BANDS, STRESS_HORIZONS, CLUSTER_GAP_SESSIONS, RISK_RULE, buildStressOutcomes, meanStandardError, stressBandOf, stressWindowRisk, stressRiskSummary } from '../src/domain/market/signal/stress-outcomes.js';
import { SCENARIO_OUTCOMES_SCHEMA, STRESS_OUTCOMES_SCHEMA } from '../src/domain/scenarios/outcome-fingerprints.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTCOME_STAMPS_PATH = 'src/domain/scenarios/outcome-stamps.js';

/** The stamps the current code defines. */
export function computeOutcomeStamps() {
  return {
    themeStage: definitionFingerprint('theme-stage-outcomes', { schema: SCENARIO_OUTCOMES_SCHEMA, rule: THEME_STAGE_RULE, bands: OUTCOME_BANDS, states: Object.keys(THEME_STATES),
      horizon: THEME_OUTCOME_HORIZON, drawdownPct: DRAWDOWN_PCT, code: [themeStateOf, themeStateOutcomes, summarise, summariseOutcomes, quantile, baseRate, windowDrawdown] }),
    branches: definitionFingerprint('branch-analogs', { schema: SCENARIO_OUTCOMES_SCHEMA, method: ANALOG_METHOD, horizons: [20, 63], drawdownPct: DRAWDOWN_PCT,
      analogs: Object.fromEntries(Object.entries(BRANCH_ANALOGS).map(([id, analog]) => [id, { label: analog.label, needs: analog.needs, test: analog.test }])),
      code: [analogScan, analogOutcomeHistory, summarise, summariseOutcomes, quantile, baseRate, alignCloses, attachMonthlyRate, windowDrawdown] }),
    corrections: definitionFingerprint('correction-base-rates', { schema: SCENARIO_OUTCOMES_SCHEMA, rule: CORRECTION_RULE, code: [correctionEpisodes, correctionBaseRates] }),
    stress: definitionFingerprint('stress-outcomes', { schema: STRESS_OUTCOMES_SCHEMA, bands: STRESS_BANDS, horizons: STRESS_HORIZONS, clusterGap: CLUSTER_GAP_SESSIONS,
      risk: RISK_RULE, code: [buildStressOutcomes, meanStandardError, stressBandOf, stressWindowRisk, stressRiskSummary] })
  };
}

export function renderOutcomeStampsModule(stamps) {
  return `// Generated by scripts/build-outcome-stamps.mjs — do not edit by hand; rerun it with --write after changing a definition.
// The definition stamps of the weekly long-history artifacts (scenario-outcomes.json, stress-outcomes.json): producers
// stamp what they write with these, and readers use a record only when its stamp is the one here.
export const OUTCOME_STAMPS = Object.freeze(${JSON.stringify(stamps, null, 2).replace(/"([a-zA-Z]+)":/g, '$1:').replace(/"/g, "'")});
`;
}

const entry = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (entry === fileURLToPath(import.meta.url)) {
  const stamps = computeOutcomeStamps();
  const file = path.join(ROOT, OUTCOME_STAMPS_PATH);
  const next = renderOutcomeStampsModule(stamps);
  if (process.argv.includes('--write')) {
    if (readFileSync(file, 'utf8') !== next) writeFileSync(file, next);
    console.log(`outcome stamps written: ${OUTCOME_STAMPS_PATH}`);
  } else console.log(JSON.stringify(stamps, null, 2));
}
