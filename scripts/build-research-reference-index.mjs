#!/usr/bin/env node
// Generates src/domain/research/reference-index.js: the small metadata slice of the supplied-materials corpus that
// boot-time consumers read synchronously (per-route mappings for the hidden protocol bridge, the claim-ID list and
// pipeline lineage for the screener workbench). The full corpus (source packets, claim text, X-bookmark packets) is
// several hundred KB and is loaded on demand through src/domain/research/corpus-loader.js, so it stays out of the
// boot module set. `--check` fails when the committed index no longer matches the corpus.
//
//   node scripts/build-research-reference-index.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SUPPLIED_MATERIALS_REFERENCE, SUPPLIED_MATERIAL_CLAIM_IDS } from '../src/domain/research/supplied-materials.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'src/domain/research/reference-index.js');
const reference = SUPPLIED_MATERIALS_REFERENCE;
const pipeline = reference.sourceExtensions?.pipeline || {};

const meta = {
  id: reference.id,
  sourceKind: reference.sourceKind,
  operationalUse: reference.operationalUse,
  updatedAt: reference.updatedAt || null,
  sourceExtensions: {
    packetId: reference.sourceExtensions?.packetId || null,
    pipeline: { version: pipeline.version || null, requiredLineage: [...(pipeline.requiredLineage || [])] }
  },
  routeMappings: reference.routeMappings || {}
};

const body = `// GENERATED by scripts/build-research-reference-index.mjs from src/domain/research/supplied-materials.js. Do not edit.
// Boot-time metadata only; the full corpus loads on demand via ./corpus-loader.js.
const deepFreeze = (value) => {
  if (value && typeof value === 'object') { Object.values(value).forEach(deepFreeze); Object.freeze(value); }
  return value;
};

export const SUPPLIED_MATERIALS_META = deepFreeze(${JSON.stringify(meta, null, 2)});

export const SUPPLIED_MATERIAL_CLAIM_IDS = deepFreeze(${JSON.stringify([...SUPPLIED_MATERIAL_CLAIM_IDS], null, 2)});
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== body) {
    console.error('research reference index is stale: run node scripts/build-research-reference-index.mjs');
    process.exit(1);
  }
  console.log(`research reference index OK (${SUPPLIED_MATERIAL_CLAIM_IDS.length} claim ids, ${Object.keys(meta.routeMappings).length} route mappings)`);
} else {
  fs.writeFileSync(target, body);
  console.log(`wrote ${path.relative(root, target)} (${body.length} bytes)`);
}
